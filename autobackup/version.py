"""
Version management for Tethr.
Dynamically resolves application version from:
1. Environment variables (TETHR_VERSION, APP_VERSION, GITHUB_REF_NAME)
2. Embedded _version.py generated during packaging
3. Git release tags (when running from source repository)
4. Fallback default
"""
import os
import re
import subprocess
from pathlib import Path

DEFAULT_VERSION = "1.0.0"


def _clean_version(ver_str: str) -> str:
    """Strips leading 'v'/'V', whitespace, and git ref prefixes."""
    clean = ver_str.strip()
    clean = re.sub(r"^refs/tags/", "", clean)
    clean = re.sub(r"^[vV]", "", clean)
    return clean


def _get_env_version() -> str | None:
    """Checks environment variables for version specification."""
    for var in ("TETHR_VERSION", "APP_VERSION", "GITHUB_REF_NAME"):
        val = os.environ.get(var)
        if val and val.strip():
            clean = _clean_version(val)
            if re.match(r"^\d+(\.\d+)*", clean):
                return clean
    return None


def _get_baked_version() -> str | None:
    """Checks for autobackup/_version.py embedded during PyInstaller build."""
    try:
        from autobackup._version import VERSION
        if VERSION and str(VERSION).strip():
            return _clean_version(str(VERSION))
    except ImportError:
        pass
    return None


def _get_git_version() -> str | None:
    """Extracts latest version tag from Git."""
    repo_dir = Path(__file__).resolve().parent.parent
    commands = [
        ["git", "tag", "--merged", "HEAD", "--sort=-v:refname"],
        ["git", "tag", "-l", "--sort=-v:refname"],
        ["git", "describe", "--tags", "--abbrev=0"],
    ]

    for cmd in commands:
        try:
            out = subprocess.check_output(
                cmd,
                cwd=str(repo_dir),
                stderr=subprocess.DEVNULL,
                encoding="utf-8"
            )
            for line in out.splitlines():
                clean = _clean_version(line)
                if re.match(r"^\d+(\.\d+)*", clean):
                    return clean
        except Exception:
            continue

    return None


_CACHED_VERSION: str | None = None


def get_version(use_cache: bool = True) -> str:
    """
    Resolves and returns the dynamic application version.
    Searches env variables -> baked file -> git release tags -> fallback.
    """
    global _CACHED_VERSION
    if use_cache and _CACHED_VERSION is not None:
        return _CACHED_VERSION

    # 1. Environment variable override (CI/Build environments)
    env_ver = _get_env_version()
    if env_ver:
        _CACHED_VERSION = env_ver
        return _CACHED_VERSION

    # 2. Baked / generated version file (e.g. inside PyInstaller frozen bundle)
    baked_ver = _get_baked_version()
    if baked_ver:
        _CACHED_VERSION = baked_ver
        return _CACHED_VERSION

    # 3. Dynamic query from Git release tags (development from source)
    git_ver = _get_git_version()
    if git_ver:
        _CACHED_VERSION = git_ver
        return _CACHED_VERSION

    # 4. Fallback default
    _CACHED_VERSION = DEFAULT_VERSION
    return _CACHED_VERSION


def write_version_file(version: str, target_file: Path | None = None) -> Path:
    """
    Writes autobackup/_version.py with the resolved version.
    Called by build scripts or PyInstaller spec prior to bundling.
    """
    if target_file is None:
        target_file = Path(__file__).resolve().parent / "_version.py"

    clean_ver = _clean_version(version)
    target_file.write_text(
        f'# Auto-generated by build process. Do not commit to version control.\n'
        f'VERSION = "{clean_ver}"\n',
        encoding="utf-8"
    )
    return target_file
